#pragma warning(disable:4996)
#pragma once

//-----------------------------------------------------------------------------
// キャラクター汎用スーパークラス
// 魔王・勇者で共通する処理を管理する
//-----------------------------------------------------------------------------

#include "GameEngine_Ver3_83.h"
#include <cmath>

class BChara : public BTask
{
public:
    //-------------------------------------------------------------------------
    // 勝者を管理する変数
    //-------------------------------------------------------------------------

    // -1：勝者なし
    //  0：プレイヤー1
    //  1：プレイヤー2
    static int winner;
    //-------------------------------------------------------------------------
    // キャラクターの向き
    //-------------------------------------------------------------------------
    enum class Direction
    {
        Down,       // 下
        Left,       // 左
        Right,      // 右
        Up          // 上
    };

    //-------------------------------------------------------------------------
    // キャラクターの行動状態
    //-------------------------------------------------------------------------
    enum class ActionState
    {
        Move,       // 通常移動
        Attack,     // 攻撃中
        Recovery,   // 攻撃後の硬直
        CoolTime    // クールタイム
    };
    struct DrawInfo
    {
        ML::Box2D draw;
        ML::Box2D src;
        ML::Color color;
    };
    //-------------------------------------------------------------------------
    // コンストラクタ・デストラクタ
    //-------------------------------------------------------------------------
    BChara();
    virtual ~BChara();

    //-------------------------------------------------------------------------
    // 位置情報
    //-------------------------------------------------------------------------

    // 画面座標（既存コードとの互換性用）
    ML::Vec2 pos;

    // 現在のピクセル座標
    float posX;
    float posY;

    // 現在のマス
    int mapX;
    int mapY;

    // 移動先のマス
    int targetX;
    int targetY;

    // 移動中かどうか
    bool moving;

    //-------------------------------------------------------------------------
    // 移動情報
    //-------------------------------------------------------------------------

    // 移動速度
    float moveSpeed;

    // キャラクターの向き
    Direction direction;

    //-------------------------------------------------------------------------
    // 行動状態
    //-------------------------------------------------------------------------

    ActionState actionState;

    // 現在の状態の残り時間
    int actionTimer;

    // 攻撃時間
    int attackTime;

    // 攻撃後の硬直時間
    int recoveryTime;

    // クールタイム
    int coolTime;

    //-------------------------------------------------------------------------
    // アニメーション
    //-------------------------------------------------------------------------

    // モーションの種類
    enum class Motion
    {
        Idle,       // 待機
        Walk,       // 移動
        Attack      // 攻撃
    };

    Motion motion;

    // 移動・アニメーションカウンター
    int moveCnt;
    int animCnt;

    //-------------------------------------------------------------------------
    // 共通処理
    //-------------------------------------------------------------------------

    // モーション変更
    bool UpdateMotion(Motion nm_);

    // キャラクターの位置設定
    void SetPosition(int x, int y);

    // 移動方向設定
    void SetMoveDirection(int dx, int dy);

    // 移動処理
    void Move();

    // 壁判定
    bool CheckWall(int x, int y);

    // 行動状態変更
    void ChangeActionState(ActionState nextState, int time);

    // 行動状態更新
    void UpdateActionState();

    // 攻撃開始
    void StartAttack(int time);

    // 攻撃後の硬直
    void StartRecovery();

    // クールタイム開始
    void StartCoolTime();

    // 移動可能か
    bool CanMove() const;

    // 攻撃可能か
    bool CanAttack() const;

    // 接触判定
    bool CheckCollision(float x, float y, float size);

    // 移動速度変更
    void SetMoveSpeed(float speed);
};