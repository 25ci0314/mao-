    //------------------------------------------------------------------
    // マップの描画
    //------------------------------------------------------------------
    void Object::Render2D_AF()
    {
        // リソースがない場合は描画しない
        if (!res)
        {
            return;
        }

        //--------------------------------------------------------------
        // ① 外壁と迷路の壁を描画
        //--------------------------------------------------------------
        if (res->img)
        {
            for (int y = 0; y < MAP_H; y++)
            {
                for (int x = 0; x < MAP_W; x++)
                {
                    // 壁でないマスは描画しない
                    if (map[y][x] != 1)
                    {
                        continue;
                    }

                    // 家が配置されているマスかどうか
                    bool house = false;

                    //--------------------------------------------------
                    // 上下の家の位置を確認
                    //--------------------------------------------------
                    for (int i = 0; i < 5; i++)
                    {
                        int hx = 5 + i * 6;

                        if (x >= hx && x < hx + 3)
                        {
                            if ((y >= 1 && y <= 2) ||
                                (y >= 12 && y <= 13))
                            {
                                house = true;
                            }
                        }
                    }

                    //--------------------------------------------------
                    // 左右の家の位置を確認
                    //--------------------------------------------------
                    if (((x >= 1 && x <= 2) ||
                        (x >= 35 && x <= 36)) &&
                        ((y >= 4 && y <= 5) ||
                            (y >= 8 && y <= 9)))
                    {
                        house = true;
                    }

                    // 家の場所には壁画像を描画しない
                    if (house)
                    {
                        continue;
                    }

                    // 壁の描画位置
                    ML::Box2D draw(
                        boardX + x * cellSize,
                        boardY + y * cellSize,
                        cellSize,
                        cellSize
                    );

                    // 壁画像の切り取り範囲
                    ML::Box2D src(12, 74, 128, 135);

                    // 壁を描画
                    res->img->Draw(draw, src);
                }
            }
        }

        //--------------------------------------------------------------
        // ② 上側と下側の家を描画
        //--------------------------------------------------------------
        // 上下それぞれ5軒
        // 家の大きさは横3マス×縦2マス
        //--------------------------------------------------------------
        for (int i = 0; i < 5; i++)
        {
            // 家の配置位置
            int x = 5 + i * 6;

            // ピクセル座標に変換
            int px = boardX + x * cellSize;

            //----------------------------------------------------------
            // 上側の家
            // ドアが下向き（迷路の内側）
            //----------------------------------------------------------
            if (res->houseDown)
            {
                ML::Box2D draw(
                    px,
                    boardY + cellSize,
                    3 * cellSize,
                    2 * cellSize
                );

                // 家画像全体を使用
                ML::Box2D src(0, 0, 260, 225);

                res->houseDown->Draw(draw, src);
            }

            //----------------------------------------------------------
            // 下側の家
            // 背面画像を使用
            //----------------------------------------------------------
            if (res->houseUp)
            {
                ML::Box2D draw(
                    px,
                    boardY + 12 * cellSize,
                    3 * cellSize,
                    2 * cellSize
                );

                ML::Box2D src(0, 0, 262, 246);

                res->houseUp->Draw(draw, src);
            }
        }

        //--------------------------------------------------------------
        // ③ 左側と右側の家を描画
        //--------------------------------------------------------------
        // 左右それぞれ2軒
        // 家の大きさは横2マス×縦2マス
        //--------------------------------------------------------------

        // 家を置く縦方向のマス
        const int sideRows[2] = { 4, 8 };

        for (int i = 0; i < 2; i++)
        {
            int y = sideRows[i];

            // ピクセル座標に変換
            int py = boardY + y * cellSize;

            //----------------------------------------------------------
            // 左側の家
            // ドアが右向き（迷路の内側）
            //----------------------------------------------------------
            if (res->houseRight)
            {
                ML::Box2D draw(
                    boardX + cellSize,
                    py,
                    2 * cellSize,
                    2 * cellSize
                );

                ML::Box2D src(0, 0, 246, 241);

                res->houseRight->Draw(draw, src);
            }

            //----------------------------------------------------------
            // 右側の家
            // ドアが左向き（迷路の内側）
            //----------------------------------------------------------
            if (res->houseLeft)
            {
                ML::Box2D draw(
                    boardX + 35 * cellSize,
                    py,
                    2 * cellSize,
                    2 * cellSize
                );

                ML::Box2D src(0, 0, 249, 237);

                res->houseLeft->Draw(draw, src);
            }
        }
    }

    //------------------------------------------------------------------
    // マップデータの作成
    //------------------------------------------------------------------
    void Object::Board_Initialize()
    {
        //--------------------------------------------------------------
        // ① 全マスを通路にする
        //--------------------------------------------------------------
        for (int y = 0; y < MAP_H; y++)
        {
            for (int x = 0; x < MAP_W; x++)
            {
                map[y][x] = 0;
            }
        }

        //--------------------------------------------------------------
        // ② 外周を壁で囲む
        //--------------------------------------------------------------

        // 上下の外壁
        for (int x = 0; x < MAP_W; x++)
        {
            map[0][x] = 1;
            map[MAP_H - 1][x] = 1;
        }

        // 左右の外壁
        for (int y = 0; y < MAP_H; y++)
        {
            map[y][0] = 1;
            map[y][MAP_W - 1] = 1;
        }

        //--------------------------------------------------------------
        // ③ 上下の家を配置
        //--------------------------------------------------------------
        // 上側：1～2行目
        // 下側：12～13行目
        // 家の前には通路を残す
        //--------------------------------------------------------------
        for (int i = 0; i < 5; i++)
        {
            int hx = 5 + i * 6;

            for (int dx = 0; dx < 3; dx++)
            {
                // 上側の家
                map[1][hx + dx] = 1;
                map[2][hx + dx] = 1;

                // 下側の家
                map[12][hx + dx] = 1;
                map[13][hx + dx] = 1;
            }
        }

        //--------------------------------------------------------------
        // ④ 左右の家を配置
        //--------------------------------------------------------------
        // 左側：1～2列目
        // 右側：35～36列目
        //--------------------------------------------------------------
        const int sideRows[2] = { 4, 8 };

        for (int i = 0; i < 2; i++)
        {
            for (int dy = 0; dy < 2; dy++)
            {
                // 左側の家
                for (int x = 1; x <= 2; x++)
                {
                    map[sideRows[i] + dy][x] = 1;
                }

                // 右側の家
                for (int x = 35; x <= 36; x++)
                {
                    map[sideRows[i] + dy][x] = 1;
                }
            }
        }

        //--------------------------------------------------------------
        // ⑤ 迷路の内部に壁を配置
        //--------------------------------------------------------------
        // 壁を短く配置して通路が塞がらないようにする
        //--------------------------------------------------------------

        // 壁を配置する横方向の位置
        const int wallX[5] = { 7, 13, 19, 25, 31 };

        // 壁を配置する縦方向の位置
        const int wallY[2] = { 5, 9 };

        for (int iy = 0; iy < 2; iy++)
        {
            for (int ix = 0; ix < 5; ix++)
            {
                int x = wallX[ix];
                int y = wallY[iy];

                // 横に2マスの壁
                map[y][x] = 1;
                map[y][x + 1] = 1;

                // 壁の枝を交互に上下へ伸ばす
                if ((ix + iy) % 2 == 0)
                {
                    map[y + 1][x] = 1;
                }
                else
                {
                    map[y - 1][x + 1] = 1;
                }
            }
        }

        //--------------------------------------------------------------
        // ⑥ 魔王の初期位置を通路にする
        //--------------------------------------------------------------
        // 初期位置は (3, 2)
        //--------------------------------------------------------------
        map[2][3] = 0;
    }

    //------------------------------------------------------------------
    // 指定したマスが壁かどうか判定
    //------------------------------------------------------------------
    bool Object::IsWall(int x, int y)
    {
        // マップの範囲外は通行不可
        if (x < 0 || x >= MAP_W ||
            y < 0 || y >= MAP_H)
        {
            return true;
        }

        // 1なら壁、0なら通路
        return map[y][x] == 1;
    }

    //------------------------------------------------------------------
    // マップタスクの生成
    //------------------------------------------------------------------
    Object::SP Object::Create(bool flagGameEnginePushBack_)
    {
        Object::SP ob = Object::SP(new Object());

        if (ob)
        {
            // 自分自身を登録
            ob->me = ob;

            // ゲームエンジンに追加
            if (flagGameEnginePushBack_)
            {
                ge->PushBack(ob);
            }

            // 初期化
            if (!ob->B_Initialize())
            {
                ob->Kill();
            }
        }

        return ob;
    }

