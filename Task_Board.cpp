    //------------------------------------------------------------------
    // リソースの生成
    //------------------------------------------------------------------
    Resource::SP Resource::Create()
    {
        // すでに存在する場合は再利用
        if (auto sp = instance.lock())
        {
            return sp;
        }

        // 存在しない場合は新しく作成
        Resource::SP sp(new Resource());

        if (sp)
        {
            sp->Initialize();
            instance = sp;
        }

        return sp;
    }

