//-----------------------------------------------------------------------------
// キャラクター汎用スーパークラス
// 魔王・勇者の移動・攻撃・硬直などを管理
//-----------------------------------------------------------------------------

#include "BChara.h"
#include "MyPG.h"
#include "Task_Board.h"

#include <cmath>
#include <cstdlib>

//-----------------------------------------------------------------------------
// コンストラクタ
//-----------------------------------------------------------------------------
BChara::BChara()
{
    //---------------------------------------------------------------------
    // 初期位置
    //---------------------------------------------------------------------
    posX = 0.0f;
    posY = 0.0f;

    mapX = 0;
    mapY = 0;

    targetX = 0;
    targetY = 0;

    moving = false;

    //---------------------------------------------------------------------
    // 移動速度
    //---------------------------------------------------------------------
    moveSpeed = 2.0f;

    direction = Direction::Down;

    //---------------------------------------------------------------------
    // 行動状態
    //---------------------------------------------------------------------
    actionState = ActionState::Move;

    actionTimer = 0;

    // 攻撃モーション18フレーム
    attackTime = 18;

    // 攻撃後の硬直120フレーム
    recoveryTime = 120;

    // クールタイム30フレーム
    coolTime = 30;

    //---------------------------------------------------------------------
    // アニメーション
    //---------------------------------------------------------------------
    motion = Motion::Idle;

    moveCnt = 0;
    animCnt = 0;
}

//-----------------------------------------------------------------------------
// デストラクタ
//-----------------------------------------------------------------------------
BChara::~BChara()
{
}

//-----------------------------------------------------------------------------
// モーションの更新
// 変更がなければfalse
//-----------------------------------------------------------------------------
bool BChara::UpdateMotion(Motion nm_)
{
    if (nm_ == motion)
    {
        return false;
    }

    motion = nm_;

    moveCnt = 0;
    animCnt = 0;

    return true;
}

//-----------------------------------------------------------------------------
// キャラクターの位置を設定
//-----------------------------------------------------------------------------
void BChara::SetPosition(int x, int y)
{
    mapX = x;
    mapY = y;

    targetX = x;
    targetY = y;

    //---------------------------------------------------------------------
    // マップ座標からピクセル座標に変換
    //---------------------------------------------------------------------
    auto board = ge->GetTask<Board::Object>(
        Board::defGroupName,
        Board::defName
    );

    if (board)
    {
        posX = static_cast<float>(
            board->boardX + x * board->cellSize
            );

        posY = static_cast<float>(
            board->boardY + y * board->cellSize
            );
    }

    moving = false;
}

//-----------------------------------------------------------------------------
// 移動方向を設定
//-----------------------------------------------------------------------------
void BChara::SetMoveDirection(int dx, int dy)
{
    //---------------------------------------------------------------------
    // 移動できない状態なら処理しない
    //---------------------------------------------------------------------
    if (!CanMove())
    {
        return;
    }

    //---------------------------------------------------------------------
    // 移動中は新しい方向を受け付けない
    //---------------------------------------------------------------------
    if (moving)
    {
        return;
    }

    //---------------------------------------------------------------------
    // 上下左右の1マス移動のみ許可
    //---------------------------------------------------------------------
    if (std::abs(dx) + std::abs(dy) != 1)
    {
        return;
    }

    //---------------------------------------------------------------------
    // キャラクターの向きを変更
    //---------------------------------------------------------------------
    if (dx > 0)
    {
        direction = Direction::Right;
    }
    else if (dx < 0)
    {
        direction = Direction::Left;
    }
    else if (dy > 0)
    {
        direction = Direction::Down;
    }
    else if (dy < 0)
    {
        direction = Direction::Up;
    }

    //---------------------------------------------------------------------
    // 移動先のマスを計算
    //---------------------------------------------------------------------
    int nextX = mapX + dx;
    int nextY = mapY + dy;

    //---------------------------------------------------------------------
    // 壁なら移動しない
    //---------------------------------------------------------------------
    if (CheckWall(nextX, nextY))
    {
        return;
    }

    //---------------------------------------------------------------------
    // 移動先を設定
    //---------------------------------------------------------------------
    targetX = nextX;
    targetY = nextY;

    moving = true;

    UpdateMotion(Motion::Walk);
}

//-----------------------------------------------------------------------------
// マス目に沿って滑らかに移動
//-----------------------------------------------------------------------------
void BChara::Move()
{
    if (!moving)
    {
        UpdateMotion(Motion::Idle);
        return;
    }

    //---------------------------------------------------------------------
    // マップ情報を取得
    //---------------------------------------------------------------------
    auto board = ge->GetTask<Board::Object>(
        Board::defGroupName,
        Board::defName
    );

    if (!board)
    {
        return;
    }

    //---------------------------------------------------------------------
    // 移動先のピクセル座標
    //---------------------------------------------------------------------
    float goalX = static_cast<float>(
        board->boardX + targetX * board->cellSize
        );

    float goalY = static_cast<float>(
        board->boardY + targetY * board->cellSize
        );

    float dx = goalX - posX;
    float dy = goalY - posY;

    float distance = std::sqrt(dx * dx + dy * dy);

    //---------------------------------------------------------------------
    // 移動先に到着
    //---------------------------------------------------------------------
    if (distance <= moveSpeed)
    {
        posX = goalX;
        posY = goalY;

        mapX = targetX;
        mapY = targetY;

        moving = false;

        UpdateMotion(Motion::Idle);

        return;
    }

    //---------------------------------------------------------------------
    // 移動先へ進む
    //---------------------------------------------------------------------
    posX += dx / distance * moveSpeed;
    posY += dy / distance * moveSpeed;

    moveCnt++;
    animCnt++;
}

//-----------------------------------------------------------------------------
// 壁判定
//-----------------------------------------------------------------------------
bool BChara::CheckWall(int x, int y)
{
    auto board = ge->GetTask<Board::Object>(
        Board::defGroupName,
        Board::defName
    );

    if (!board)
    {
        return true;
    }

    return board->IsWall(x, y);
}

//-----------------------------------------------------------------------------
// 行動状態を変更
//-----------------------------------------------------------------------------
void BChara::ChangeActionState(
    ActionState nextState,
    int time)
{
    actionState = nextState;
    actionTimer = time;
}

//-----------------------------------------------------------------------------
// 行動状態を更新
//-----------------------------------------------------------------------------
void BChara::UpdateActionState()
{
    //---------------------------------------------------------------------
    // 通常移動中は何もしない
    //---------------------------------------------------------------------
    if (actionState == ActionState::Move)
    {
        return;
    }

    //---------------------------------------------------------------------
    // 残り時間を減らす
    //---------------------------------------------------------------------
    if (actionTimer > 0)
    {
        actionTimer--;
    }

    if (actionTimer > 0)
    {
        return;
    }

    //---------------------------------------------------------------------
    // 状態に応じて次の状態へ変更
    //---------------------------------------------------------------------
    switch (actionState)
    {
    case ActionState::Attack:

        StartRecovery();

        break;

    case ActionState::Recovery:

        StartCoolTime();

        break;

    case ActionState::CoolTime:

        ChangeActionState(ActionState::Move, 0);

        UpdateMotion(Motion::Idle);

        break;

    default:
        break;
    }
}

//-----------------------------------------------------------------------------
// 攻撃開始
//-----------------------------------------------------------------------------
void BChara::StartAttack(int time)
{
    if (!CanAttack())
    {
        return;
    }

    //---------------------------------------------------------------------
    // 移動中の攻撃は行わない
    //---------------------------------------------------------------------
    if (moving)
    {
        return;
    }

    ChangeActionState(ActionState::Attack, time);

    UpdateMotion(Motion::Attack);
}

//-----------------------------------------------------------------------------
// 攻撃後の硬直
//-----------------------------------------------------------------------------
void BChara::StartRecovery()
{
    ChangeActionState(
        ActionState::Recovery,
        recoveryTime
    );

    UpdateMotion(Motion::Idle);
}

//-----------------------------------------------------------------------------
// クールタイム開始
//-----------------------------------------------------------------------------
void BChara::StartCoolTime()
{
    ChangeActionState(
        ActionState::CoolTime,
        coolTime
    );
}

//-----------------------------------------------------------------------------
// 移動可能か確認
//-----------------------------------------------------------------------------
bool BChara::CanMove() const
{
    return actionState == ActionState::Move;
}

//-----------------------------------------------------------------------------
// 攻撃可能か確認
//-----------------------------------------------------------------------------
bool BChara::CanAttack() const
{
    return actionState == ActionState::Move;
}

//-----------------------------------------------------------------------------
// キャラクター同士の接触判定
//-----------------------------------------------------------------------------
bool BChara::CheckCollision(float x, float y, float size)
{
    const float charaSize = 32.0f;

    bool hitX =
        posX < x + size &&
        posX + charaSize > x;

    bool hitY =
        posY < y + size &&
        posY + charaSize > y;

    return hitX && hitY;
}

//-----------------------------------------------------------------------------
// 移動速度を変更
//-----------------------------------------------------------------------------
void BChara::SetMoveSpeed(float speed)
{
    if (speed > 0.0f)
    {
        moveSpeed = speed;
    }
}
