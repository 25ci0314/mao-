    //-------------------------------------------------------------------
    //指定したマスが通路かどうか
    //-------------------------------------------------------------------
    bool Object::IsRoad(int x, int y)
    {
        //マップタスクを取得
        auto board = ge->GetTask<Board::Object>(
            Board::defGroupName,
            Board::defName
        );

        //マップが存在しない場合
        if (board == nullptr)
        {
            return false;
        }

        //壁や家の場合
        if (board->IsWall(x, y))
        {
            return false;
        }

        //通路の場合
        return true;
    }

    //-------------------------------------------------------------------
    //アイテムを生成できる場所か
    //-------------------------------------------------------------------
    bool Object::CanSpawn(int x, int y)
    {
        //通路以外には生成しない
        if (!IsRoad(x, y))
        {
            return false;
        }

        //---------------------------------------------------------------
        //ほかのアイテムと重なっていないか確認
        //---------------------------------------------------------------
        for (int i = 0; i < MAX_ITEMS; i++)
        {
            //アイテムが存在している場合
            if (items[i].active)
            {
                //同じマスにアイテムがある場合
                if (items[i].mapX == x &&
                    items[i].mapY == y)
                {
                    return false;
                }
            }
        }

        //---------------------------------------------------------------
        //爆弾と重なっていないか確認
        //---------------------------------------------------------------
        if (bombActive)
        {
            //同じマスに爆弾がある場合
            if (bombX == x && bombY == y)
            {
                return false;
            }
        }

        //アイテムを生成できる
        return true;
    }

    //-------------------------------------------------------------------
    //ランダムな生成場所を探す
    //-------------------------------------------------------------------
    bool Object::FindSpawnPoint(int& x, int& y)
    {
        //マップタスクを取得
        auto board = ge->GetTask<Board::Object>(
            Board::defGroupName,
            Board::defName
        );

        if (board == nullptr)
        {
            return false;
        }

        //魔王タスクを取得
        auto player = ge->GetTask<Player::Object>(
            Player::defGroupName,
            Player::defName
        );

        //---------------------------------------------------------------
        //生成可能なマスを保存する配列
        //---------------------------------------------------------------
        int roadX[Board::Object::MAP_W * Board::Object::MAP_H];
        int roadY[Board::Object::MAP_W * Board::Object::MAP_H];

        //生成可能なマスの数
        int count = 0;

        //---------------------------------------------------------------
        //マップ全体を調べる
        //---------------------------------------------------------------
        for (int iy = 0; iy < Board::Object::MAP_H; iy++)
        {
            for (int ix = 0; ix < Board::Object::MAP_W; ix++)
            {
                //生成できないマスは飛ばす
                if (!CanSpawn(ix, iy))
                {
                    continue;
                }

                //家の配達場所には生成しない
                if (board->IsDeliveryPoint(ix, iy))
                {
                    continue;
                }

                //魔王の現在位置には生成しない
                if (player != nullptr)
                {
                    if (player->mapX == ix &&
                        player->mapY == iy)
                    {
                        continue;
                    }
                }

                //生成可能なマスの座標を保存
                roadX[count] = ix;
                roadY[count] = iy;

                //生成可能なマスの数を加算
                count++;
            }
        }

        //生成できる場所がない場合
        if (count == 0)
        {
            return false;
        }

        //---------------------------------------------------------------
        //生成場所をランダムに選択
        //---------------------------------------------------------------

        //学校の乱数ライブラリを使用
        int num = GetRandom(0, count - 1);

        //選ばれたマスの座標を渡す
        x = roadX[num];
        y = roadY[num];

        return true;
    }

    //-------------------------------------------------------------------
    //指定した番号の荷物が存在するか
    //-------------------------------------------------------------------
    bool Object::IsPackageNumber(int number_)
    {
        //---------------------------------------------------------------
        //マップ上の荷物を確認
        //---------------------------------------------------------------
        for (int i = 0; i < MAX_ITEMS; i++)
        {
            //存在している荷物か確認
            if (items[i].active &&
                items[i].type == Item_Package)
            {
                //同じ番号の荷物が存在する場合
                if (items[i].number == number_)
                {
                    return true;
                }
            }
        }

        //---------------------------------------------------------------
        //魔王が持っている荷物を確認
        //---------------------------------------------------------------

        //魔王タスクを取得
        auto player = ge->GetTask<Player::Object>(
            Player::defGroupName,
            Player::defName
        );

        if (player != nullptr)
        {
            //魔王が荷物を持っている場合
            if (player->hasPackage)
            {
                //同じ番号の荷物を持っている場合
                if (player->packageNumber == number_)
                {
                    return true;
                }
            }
        }

        //指定した番号の荷物は存在しない
        return false;
    }

    //-------------------------------------------------------------------
    //指定した配達先が使用されているか
    //-------------------------------------------------------------------
    bool Object::IsDeliveryUsed(int x, int y)
    {
        //---------------------------------------------------------------
        //マップ上の荷物の配達先を確認
        //---------------------------------------------------------------
        for (int i = 0; i < MAX_ITEMS; i++)
        {
            //存在している荷物か確認
            if (items[i].active &&
                items[i].type == Item_Package)
            {
                //同じ配達先が使用されている場合
                if (items[i].deliveryX == x &&
                    items[i].deliveryY == y)
                {
                    return true;
                }
            }
        }

        //---------------------------------------------------------------
        //魔王が持っている荷物の配達先を確認
        //---------------------------------------------------------------

        //魔王タスクを取得
        auto player = ge->GetTask<Player::Object>(
            Player::defGroupName,
            Player::defName
        );

        if (player != nullptr)
        {
            //魔王が荷物を持っている場合
            if (player->hasPackage)
            {
                //同じ配達先が使用されている場合
                if (player->packageDeliveryX == x &&
                    player->packageDeliveryY == y)
                {
                    return true;
                }
            }
        }

        //指定した配達先は使用されていない
        return false;
    }

    //-------------------------------------------------------------------
    //荷物を生成
    //-------------------------------------------------------------------
    bool Object::CreatePackage()
    {
        //マップタスクを取得
        auto board = ge->GetTask<Board::Object>(
            Board::defGroupName,
            Board::defName
        );

        if (board == nullptr)
        {
            return false;
        }

        //---------------------------------------------------------------
        //使用されていない荷物の番号を探す
        //---------------------------------------------------------------

        //荷物の番号
        int number = 0;

        //1番から5番まで調べる
        for (int i = 1; i <= MAX_PACKAGE; i++)
        {
            //使用されていない番号の場合
            if (!IsPackageNumber(i))
            {
                //荷物の番号を決定
                number = i;

                break;
            }
        }

        //すべての番号が使用されている場合
        if (number == 0)
        {
            return false;
        }

        //---------------------------------------------------------------
        //使用されていない配達先を探す
        //---------------------------------------------------------------

        //使用可能な配達先を保存する配列
        int deliveryList[Board::Object::MAX_DELIVERY];

        //使用可能な配達先の数
        int count = 0;

        //すべての配達先を調べる
        for (int i = 0; i < Board::Object::MAX_DELIVERY; i++)
        {
            //配達先が通路でなければ飛ばす
            if (board->IsWall(
                board->deliveryX[i],
                board->deliveryY[i]))
            {
                continue;
            }

            //まだ使用されていない配達先の場合
            if (!IsDeliveryUsed(
                board->deliveryX[i],
                board->deliveryY[i]))
            {
                //使用可能な配達先を保存
                deliveryList[count] = i;

                count++;
            }
        }

        //使用可能な配達先がない場合
        if (count == 0)
        {
            return false;
        }

        //配達先をランダムに選択
        int num = deliveryList[GetRandom(0, count - 1)];

        //---------------------------------------------------------------
        //空いているアイテム配列を探す
        //---------------------------------------------------------------
        for (int i = 0; i < MAX_ITEMS; i++)
        {
            //使用されていない配列の場合
            if (!items[i].active)
            {
                //荷物の生成座標
                int x;
                int y;

                //ランダムな生成場所を探す
                if (!FindSpawnPoint(x, y))
                {
                    return false;
                }

                //-------------------------------------------------------
                //荷物の情報を設定
                //-------------------------------------------------------

                //アイテムの種類
                items[i].type = Item_Package;

                //荷物の生成位置
                items[i].mapX = x;
                items[i].mapY = y;

                //荷物の初期価値
                items[i].value = 1500;

                //荷物の番号
                items[i].number = number;

                //荷物の配達先
                items[i].deliveryX = board->deliveryX[num];
                items[i].deliveryY = board->deliveryY[num];

                //荷物を有効にする
                items[i].active = true;

                //荷物の生成に成功
                return true;
            }
        }

        //荷物の生成に失敗
        return false;
    }

    //-------------------------------------------------------------------
    //勇者専用アイテムを生成
    //-------------------------------------------------------------------
    void Object::CreateRandomItem()
    {
        //---------------------------------------------------------------
        //アイテムの種類をランダムに決定
        //---------------------------------------------------------------

        //0 = 爆弾
        //1 = 停止
        //2 = スピードアップ
        //3 = 攻撃力アップ
        int type = GetRandom(0, 3);

        //---------------------------------------------------------------
        //空いているアイテム配列を探す
        //---------------------------------------------------------------
        for (int i = 0; i < MAX_ITEMS; i++)
        {
            if (!items[i].active)
            {
                //アイテムの生成座標
                int x;
                int y;

                //ランダムな生成場所を探す
                if (!FindSpawnPoint(x, y))
                {
                    return;
                }

                //アイテムの種類
                items[i].type = (ItemType)type;

                //アイテムの生成位置
                items[i].mapX = x;
                items[i].mapY = y;

                //勇者専用アイテムには価値がない
                items[i].value = 0;

                //勇者専用アイテムには番号がない
                items[i].number = 0;

                //勇者専用アイテムには配達先がない
                items[i].deliveryX = -1;
                items[i].deliveryY = -1;

                //アイテムを有効にする
                items[i].active = true;

                return;
            }
        }
    }

    //-------------------------------------------------------------------
    //荷物が配達または破壊されたとき
    //-------------------------------------------------------------------
    void Object::RemovePackage()
    {
        //なくなった荷物の数を加算
        removedPackageCount++;

        //荷物が2個なくなった場合
        if (removedPackageCount >= 2)
        {
            //なくなった荷物の数を減らす
            removedPackageCount -= 2;

            //新しい荷物を2個補充する
            pendingPackageCount += 2;
        }
    }

    //-------------------------------------------------------------------
    //勇者がアイテムを拾う
    //-------------------------------------------------------------------
    void Object::PickupHeroItem(int x, int y)
    {
        //すでにアイテムを持っている場合
        if (heroHasItem)
        {
            return;
        }

        //---------------------------------------------------------------
        //マップ上のアイテムを探す
        //---------------------------------------------------------------
        for (int i = 0; i < MAX_ITEMS; i++)
        {
            //存在している勇者専用アイテムか確認
            if (items[i].active &&
                items[i].type != Item_Package)
            {
                //勇者とアイテムが同じマスにいる場合
                if (items[i].mapX == x &&
                    items[i].mapY == y)
                {
                    //アイテムの種類を取得
                    heroItem = items[i].type;

                    //勇者がアイテムを持つ
                    heroHasItem = true;

                    //マップ上からアイテムを消す
                    items[i].active = false;

                    return;
                }
            }
        }
    }

    //-------------------------------------------------------------------
    //勇者がアイテムを使用する
    //-------------------------------------------------------------------
    void Object::UseHeroItem(int x, int y)
    {
        //アイテムを持っていない場合
        if (!heroHasItem)
        {
            return;
        }

        //---------------------------------------------------------------
        //爆弾アイテム
        //---------------------------------------------------------------
        if (heroItem == Item_Bomb)
        {
            //爆弾が設置されていない場合
            if (!bombActive)
            {
                //爆弾を設置する
                bombActive = true;

                //爆弾の設置座標
                bombX = x;
                bombY = y;

                //180フレーム後に爆発
                //60FPSの場合は3秒
                bombTimer = 180;

                //アイテムを消費する
                heroHasItem = false;
            }
        }

        //---------------------------------------------------------------
        //魔王の動きを止めるアイテム
        //---------------------------------------------------------------
        else if (heroItem == Item_Stop)
        {
            //300フレーム停止
            //60FPSの場合は5秒
            stopTimer = 300;

            //アイテムを消費する
            heroHasItem = false;
        }

        //---------------------------------------------------------------
        //スピードアップアイテム
        //---------------------------------------------------------------
        else if (heroItem == Item_Speed)
        {
            //300フレームスピードアップ
            speedTimer = 300;

            //アイテムを消費する
            heroHasItem = false;
        }

        //---------------------------------------------------------------
        //攻撃力アップアイテム
        //---------------------------------------------------------------
        else if (heroItem == Item_Power)
        {
            //300フレーム攻撃力アップ
            powerTimer = 300;

            //アイテムを消費する
            heroHasItem = false;
        }
    }

    //-------------------------------------------------------------------
    //爆弾の爆発判定
    //-------------------------------------------------------------------
    bool Object::CheckBombExplosion(int x, int y)
    {
        //爆弾が設置されていない場合
        if (!bombActive)
        {
            return false;
        }

        //爆発までの時間が0になった場合
        if (bombTimer == 0)
        {
            //爆弾が当たったかどうか
            bool hit = false;

            //爆弾と魔王が同じマスにいる場合
            if (bombX == x && bombY == y)
            {
                hit = true;
            }

            //爆弾を消す
            bombActive = false;

            //当たり判定の結果を返す
            return hit;
        }

        return false;
    }

