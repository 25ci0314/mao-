    //-------------------------------------------------------------------
    //「初期化」タスク生成時に１回だけ行う処理
    //-------------------------------------------------------------------
    bool Object::Initialize()
    {
        //スーパークラス初期化
        __super::Initialize(defGroupName, defName, true);

        //リソースクラス生成orリソース共有
        this->res = Resource::Create();

        //描画優先度
        this->render2D_Priority[1] = 0.95f;

        //---------------------------------------------------------------
        //アイテムの初期化
        //---------------------------------------------------------------
        for (int i = 0; i < MAX_ITEMS; i++)
        {
            //最初はアイテムが存在しない
            items[i].active = false;

            //アイテムの種類
            items[i].type = Item_Package;

            //アイテムの座標
            items[i].mapX = 0;
            items[i].mapY = 0;

            //荷物の価値
            items[i].value = 0;

            //荷物の番号
            //0は番号がない状態
            items[i].number = 0;

            //荷物の配達先
            items[i].deliveryX = -1;
            items[i].deliveryY = -1;
        }

        //---------------------------------------------------------------
        //荷物関係の初期化
        //---------------------------------------------------------------

        //配達・破壊された荷物の数
        removedPackageCount = 0;

        //補充する荷物の数
        pendingPackageCount = 0;

        //---------------------------------------------------------------
        //勇者専用アイテムの初期化
        //---------------------------------------------------------------

        //アイテム生成タイマー
        spawnTimer = 0;

        //最初はアイテムを持っていない
        heroHasItem = false;

        //所持アイテムの初期値
        heroItem = Item_Bomb;

        //アイテムの効果時間
        stopTimer = 0;
        speedTimer = 0;
        powerTimer = 0;

        //---------------------------------------------------------------
        //爆弾の初期化
        //---------------------------------------------------------------

        //爆弾は設置されていない
        bombActive = false;

        //爆弾の座標
        bombX = 0;
        bombY = 0;

        //爆発までの時間
        bombTimer = 0;

        //---------------------------------------------------------------
        //ゲーム開始時に荷物を5個生成
        //---------------------------------------------------------------
        for (int i = 0; i < MAX_PACKAGE; i++)
        {
            //荷物を生成する
            if (!CreatePackage())
            {
                //生成できなかった場合は後から補充する
                pendingPackageCount++;
            }
        }

        return true;
    }

    //-------------------------------------------------------------------
    //「更新」１フレーム毎に行う処理
    //-------------------------------------------------------------------
    void Object::UpDate()
    {
        //---------------------------------------------------------------
        //荷物の補充
        //---------------------------------------------------------------

        //補充する荷物がある場合
        if (pendingPackageCount > 0)
        {
            //荷物の生成に成功した場合
            if (CreatePackage())
            {
                //補充する荷物の数を減らす
                pendingPackageCount--;
            }
        }

        //---------------------------------------------------------------
        //勇者専用アイテムの生成
        //---------------------------------------------------------------

        //生成タイマーを加算
        spawnTimer++;

        //600フレームごとに生成
        //60FPSの場合は10秒
        if (spawnTimer >= 600)
        {
            //タイマーをリセット
            spawnTimer = 0;

            //勇者専用アイテムを生成
            CreateRandomItem();
        }

        //---------------------------------------------------------------
        //アイテムの効果時間
        //---------------------------------------------------------------

        //魔王の停止時間
        if (stopTimer > 0)
        {
            stopTimer--;
        }

        //勇者のスピードアップ時間
        if (speedTimer > 0)
        {
            speedTimer--;
        }

        //勇者の攻撃力アップ時間
        if (powerTimer > 0)
        {
            powerTimer--;
        }

        //---------------------------------------------------------------
        //爆弾の爆発タイマー
        //---------------------------------------------------------------

        //爆弾が設置されている場合
        if (bombActive)
        {
            //爆発までの時間を減らす
            if (bombTimer > 0)
            {
                bombTimer--;
            }
        }
    }

    //-------------------------------------------------------------------
    //「２Ｄ描画」１フレーム毎に行う処理
    //-------------------------------------------------------------------
    void Object::Render2D_AF()
    {
        //マップタスクを取得
        auto board = ge->GetTask<Board::Object>(
            Board::defGroupName,
            Board::defName
        );

        //マップが存在しない場合
        if (board == nullptr)
        {
            return;
        }

        //画像が存在しない場合
        if (res == nullptr || res->img == nullptr)
        {
            return;
        }

        //---------------------------------------------------------------
        //荷物画像の切り取り範囲
        //左から1番、2番、3番、4番、5番
        //---------------------------------------------------------------
        ML::Box2D packageSrc[5] =
        {
            ML::Box2D(70,   180, 360, 360), //1番（変更なし）
            ML::Box2D(475,  180, 375, 360), //2番
            ML::Box2D(880,  180, 380, 360), //3番
            ML::Box2D(1285, 180, 395, 360), //4番
            ML::Box2D(1690, 180, 405, 360)  //5番
        };

        //---------------------------------------------------------------
        //マップ上の荷物を描画
        //---------------------------------------------------------------
        for (int i = 0; i < MAX_ITEMS; i++)
        {
            //存在している荷物か確認
            if (items[i].active &&
                items[i].type == Item_Package)
            {
                //荷物の番号を取得
                int number = items[i].number;

                //番号が範囲外の場合は描画しない
                if (number < 1 || number > MAX_PACKAGE)
                {
                    continue;
                }

                //マス座標を画面座標に変換
                int x = board->boardX +
                    items[i].mapX * board->cellSize;

                int y = board->boardY +
                    items[i].mapY * board->cellSize;

                //荷物の描画位置
                //32ピクセルのマスに28ピクセルで描画
                ML::Box2D draw(
                    x + 2,
                    y + 2,
                    28,
                    28
                );

                //荷物の番号に対応した画像を描画
                res->img->Draw(
                    draw,
                    packageSrc[number - 1]
                );
            }
        }

        //---------------------------------------------------------------
        //魔王が持っている荷物を描画
        //---------------------------------------------------------------

        //魔王タスクを取得
        auto player = ge->GetTask<Player::Object>(
            Player::defGroupName,
            Player::defName
        );

        //魔王が存在する場合
        if (player != nullptr)
        {
            //魔王が荷物を持っている場合
            if (player->hasPackage)
            {
                //持っている荷物の番号
                int number = player->packageNumber;

                //荷物の番号が1～5の場合
                if (number >= 1 && number <= MAX_PACKAGE)
                {
                    //-----------------------------------------------
                    //荷物の追従座標を取得
                    //-----------------------------------------------
                    float x = player->packagePosX;
                    float y = player->packagePosY;

                    //-----------------------------------------------
                    //追従中の荷物の描画位置
                    //-----------------------------------------------
                    ML::Box2D draw(
                        x + 2,
                        y + 2,
                        28,
                        28
                    );

                    //-----------------------------------------------
                    //魔王が持っている荷物を描画
                    //-----------------------------------------------
                    res->img->Draw(
                        draw,
                        packageSrc[number - 1]
                    );
                }
            }
        }

        //---------------------------------------------------------------
        //勇者専用アイテムの描画
        //画像が用意できたら追加する
        //---------------------------------------------------------------
    }

