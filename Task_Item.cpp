    //-------------------------------------------------------------------
    //タスク生成窓口
    //-------------------------------------------------------------------
    Object::SP Object::Create(bool flagGameEnginePushBack_)
    {
        Object::SP ob = Object::SP(new Object());

        if (ob)
        {
            ob->me = ob;

            if (flagGameEnginePushBack_)
            {
                //ゲームエンジンに登録
                ge->PushBack(ob);
            }

            if (!ob->B_Initialize())
            {
                //イニシャライズに失敗したらKill
                ob->Kill();

                return nullptr;
            }

            return ob;
        }

        return nullptr;
    }

