	//-------------------------------------------------------------------
	//「初期化」タスク生成時に１回だけ行う処理
	bool  Object::Initialize()
	{
		//スーパークラス初期化
		__super::Initialize(defGroupName, defName, true);
		//リソースクラス生成orリソース共有
		this->res = Resource::Create();

		//★データ初期化
		this->render2D_Priority[1] = .5f;

		this->time = this->timelimit;
		this->pos = ML::Vec2(0, 0);
		//★タスクの生成

		return  true;
	}
	//-------------------------------------------------------------------
	//「終了」タスク消滅時に１回だけ行う処理
	bool  Object::Finalize()
	{
		//★データ＆タスク解放


		if (!ge->QuitFlag() && this->nextTaskCreate) {
			//★引き継ぎタスクの生成
		}

		return  true;
	}
	//-------------------------------------------------------------------
	//「更新」１フレーム毎に行う処理
	void  Object::UpDate()
	{
		this->time--;
		if (this->time < 0) {
			this->Kill();
		}		
		tn = this->time / 60;
	}
	//-------------------------------------------------------------------
	//「２Ｄ描画」１フレーム毎に行う処理
	void  Object::Render2D_AF()
	{
		{
			ML::Box2D drawRed(-200, -130, 1920, 1080);
			ML::Box2D srcRed(0, 0, 1920, 1080);
			this->res->imgBG->Draw(
				drawRed,
				srcRed,
				ML::Color(0.85f, 1, 1, 1));
		}
		ML::Box2D draw(this->pos.x - 64, this->pos.y - 64, 128, 128);
		ML::Box2D src(this->tn * 64, 0, 64, 64);
		this->res->imgN->Draw(draw, src);
	}
